  fi
  echo "   Created $FIXTURE_PDF"
else
  echo "   Using existing $FIXTURE_PDF"
fi

DOC_UPLOAD=$(curl -sf -X POST "$API/chatbots/$CHATBOT_ID/documents" \
  -H "Authorization: Bearer $TOKEN" \
  -F "file=@$FIXTURE_PDF;type=application/pdf" \
  -F "title=Load Test Document")

echo "Document uploaded: $(echo "$DOC_UPLOAD" | jq -r '.data.id')"

# ── 4. Write env file for k6 ─────────────────────────────────────────────────
ENV_FILE="load-tests/.env.k6"
cat > "$ENV_FILE" << EOF
# Generated by setup.sh — source this before running k6
export API_BASE_URL=$API
export CHATBOT_PUBLIC_ID=$CHATBOT_PUBLIC_ID
export CHATBOT_UUID=$CHATBOT_ID
export DASHBOARD_TOKEN=$TOKEN
EOF

