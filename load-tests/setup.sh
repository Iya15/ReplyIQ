echo "==> Done. Environment written to $ENV_FILE"
echo ""
echo "To run load tests:"
echo "   source $ENV_FILE"
echo "   k6 run load-tests/scenarios/widget-chat.js"
echo "   k6 run load-tests/scenarios/document-ingestion.js"
echo "   k6 run load-tests/scenarios/dashboard-browse.js"
echo "   k6 run load-tests/scenarios/vector-search.js"
